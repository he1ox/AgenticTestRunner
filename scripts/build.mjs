#!/usr/bin/env node
// Writes every file that packages the skills for an agent harness, from two sources, so the
// rules and the metadata each live in one place:
//   - .claude-plugin/plugin.json: name, version, description, author, links, keywords (edit
//     these there; scripts/bump-version.mjs changes the version everywhere).
//   - skills/run-test-plan/scripts/agents.mjs: the Test Agent's rules and the browser servers.
//
//   claude/agents/test-agent-N.md     Claude Code's Test Agents, one per browser of the pool
//   .claude-plugin/plugin.json        + those agents and the pool (not a root .mcp.json, which
//                                     would also load as this repo's own MCP servers)
//   plugin.json + mcp.json            Agent Plugins 1.0 (Codex, Cursor, Copilot, VS Code…):
//                                     the skills and one shared browser server
//   .codex-plugin/plugin.json,
//   .agents/plugins/marketplace.json  Codex's own plugin and marketplace
//   gemini-extension.json             Gemini CLI extension with the shared browser server
//   skills/run-test-plan/references/test-agent.md
//                                     the rules for an orchestrator that runs cases inline
//
// The Test Agents live in claude/agents/, not agents/, because Gemini CLI and Cursor load an
// agents/ folder as their own subagents and these name Claude Code's tools.
// `--check` fails when a committed file is out of date (CI).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GENERIC_PREFIX, POOL_SIZE, agentBody, agentFile, mcpConfig, sharedServerConfig } from '../skills/run-test-plan/scripts/agents.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const AGENTS_DIR = join('claude', 'agents');
const json = (value) => JSON.stringify(value, null, 2) + '\n';

const claudeManifest = join('.claude-plugin', 'plugin.json');
const meta = JSON.parse(readFileSync(join(root, claudeManifest), 'utf8'));
const { name, version, description, author, homepage, repository, license, keywords } = meta;
const agentPaths = Array.from({ length: POOL_SIZE }, (_, i) => join(AGENTS_DIR, `test-agent-${i + 1}.md`));

const files = {
  ...Object.fromEntries(agentPaths.map((file, i) => [file, agentFile(i + 1)])),
  [claudeManifest]: json({
    ...meta,
    agents: agentPaths.map((file) => `./${file.split('\\').join('/')}`),
    mcpServers: mcpConfig().mcpServers,
  }),
  'plugin.json': json({
    $schema: 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json',
    name,
    version,
    description,
    author,
    homepage,
    repository,
    license,
    keywords,
  }),
  'mcp.json': json({ mcpServers: sharedServerConfig('${PLUGIN_ROOT}') }),
  [join('.codex-plugin', 'plugin.json')]: json({
    name,
    version,
    description,
    author,
    homepage,
    repository,
    license,
    keywords,
    skills: './skills/',
    mcpServers: './mcp.json',
    interface: {
      displayName: 'QA Runner',
      shortDescription: 'Run E2E test plans with browser agents and review them in a local viewer',
      developerName: author?.name,
      category: 'Developer Tools',
      capabilities: ['Interactive', 'Read', 'Write'],
      defaultPrompt: ['Run the test plan for SHOP-42.', 'Set up qa-runner for this project.'],
    },
  }),
  [join('.agents', 'plugins', 'marketplace.json')]: json({
    name: 'AgenticTestRunner',
    interface: { displayName: 'Agentic Test Runner' },
    plugins: [
      {
        name,
        source: { source: 'url', url: './' },
        policy: { installation: 'AVAILABLE', authentication: 'ON_INSTALL' },
        category: 'Developer Tools',
      },
    ],
  }),
  'gemini-extension.json': json({
    name,
    version,
    description,
    contextFileName: 'GEMINI.md',
    mcpServers: sharedServerConfig('${extensionPath}'),
  }),
  [join('skills', 'run-test-plan', 'references', 'test-agent.md')]: `<!-- Generated by scripts/build.mjs from skills/run-test-plan/scripts/agents.mjs. Do not edit. -->

# Test Agent rules

Read this only when \`next\` told you to run a batch **inline** (no subagent): from here until the
batch's final reply you are the Test Agent, and the batch prompt from \`next\` (after its \`---\`)
lists the briefs and the login. Subagents get these same rules inside their prompt.

${agentBody(GENERIC_PREFIX)}
`,
};

const stale = existsSync(join(root, AGENTS_DIR))
  ? readdirSync(join(root, AGENTS_DIR))
      .filter((f) => /^test-agent-\d+\.md$/.test(f))
      .map((f) => join(AGENTS_DIR, f))
      .filter((f) => !(f in files))
  : [];

// Line endings are ignored: a Windows checkout with core.autocrlf has CRLF files that git stores as LF.
const read = (file) => readFileSync(join(root, file), 'utf8').replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  const outdated = [
    ...Object.entries(files)
      .filter(([file, content]) => !existsSync(join(root, file)) || read(file) !== content)
      .map(([file]) => file),
    ...stale,
  ];
  if (outdated.length) {
    console.error(`out of date: ${outdated.join(', ')}. Run node scripts/build.mjs`);
    process.exit(1);
  }
  console.log('agents, manifests and references/test-agent.md are up to date');
} else {
  for (const [file, content] of Object.entries(files)) {
    mkdirSync(dirname(join(root, file)), { recursive: true });
    writeFileSync(join(root, file), content);
    console.log(`wrote ${file}`);
  }
  for (const file of stale) {
    rmSync(join(root, file));
    console.log(`removed ${file}`);
  }
}
